# Builds FallbackFont.hpp: the overlay's font for systems without Segoe UI (Wine/Proton), cut down to the
# characters the overlay texts use. Source: Noto Sans JP Regular (SIL Open Font License, see OFL.txt).
# usage: python make_fallback_font.py NotoSansJP-Regular.ttf   (needs fontTools: pip install fonttools)
import io
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

UNICODES = [
    *range(0x0020, 0x007F),  # Basic Latin
    *range(0x00A0, 0x0250),  # Latin-1 Supplement, Latin Extended-A and B
    *range(0x0370, 0x0400),  # Greek
    *range(0x0400, 0x0500),  # Cyrillic
    *range(0x2000, 0x2070),  # General Punctuation
    0x20AC, 0x2122,          # euro, trademark
    *range(0x2190, 0x2200),  # Arrows
    *range(0x25A0, 0x2600),  # Geometric Shapes (markers)
    0x2713, 0x2717,          # check marks
]

options = subset.Options()
options.layout_features = ["kern"]
options.hinting = False
options.name_IDs = ["*"]
options.name_languages = ["*"]
options.notdef_outline = True

font = TTFont(sys.argv[1])
subsetter = subset.Subsetter(options)
subsetter.populate(unicodes=UNICODES)
subsetter.subset(font)
out = io.BytesIO()
font.save(out)
data = out.getvalue()

lines = ["#pragma once",
         "// Generated by make_fallback_font.py from Noto Sans JP Regular (SIL Open Font License 1.1, see OFL.txt)",
         f"inline constexpr unsigned int FallbackFont_size = {len(data)};",
         f"inline constexpr unsigned char FallbackFont_data[{len(data)}] =",
         "{"]
for i in range(0, len(data), 32):
    lines.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
lines.append("};")
target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "FallbackFont.hpp")
with open(target, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"{target}: {len(data)} bytes")
