-- FusionFixUtils: the tests of the shared headers (the headers themselves are used in place by the fixes)
--
--   powershell -NoProfile -ExecutionPolicy Bypass -File tools\fetch-test-deps.ps1   (once: injector, hooking; ImGui is the imgui submodule)
--   premake5 vs2026
--   msbuild build\FusionFixUtils.slnx -p:Configuration=Release -p:Platform=Win32    (and x64, Debug)
--   tools\run-tests.bat Release Win32
--
-- Options:
--   --upscaler-sdks=<folder>   also compile upscaler/bridge/upscaler_bridge.cpp (x64) against the vendor SDKs in
--                              <folder>: dlss/include, fidelityfx/api/include, fidelityfx/upscalers/include

newoption {
   trigger     = "upscaler-sdks",
   value       = "FOLDER",
   description = "Folder with the NVIDIA NGX and AMD FidelityFX SDK headers, to compile the bridge's GPU side",
}

local deps = "tests/external"

-- Every header of the repository, compiled on its own as the first include of a translation unit: build/standalone
-- gets one .cpp per header (new headers are picked up at the next premake run).
local standalone = {}
for _, pattern in ipairs({ "include/*.h", "include/*.hpp", "asi_settings/*.h", "asi_settings/*.hpp", "overlay/*.hpp",
                           "automation/*.h", "automation/*.hpp", "aa/*.hpp", "upscaler/*.h", "upscaler/*.hpp",
                           "upscaler/bridge/*.h" }) do
   for _, header in ipairs(os.matchfiles(pattern)) do
      table.insert(standalone, header)
   end
end
table.sort(standalone)
os.mkdir("build/standalone")
for _, header in ipairs(standalone) do
   local name = header:gsub("[/%.]", "_") .. ".cpp"
   local text = "// Generated by premake5.lua: " .. header .. " compiles on its own\r\n#include \"../../" .. header .. "\"\r\n"
   if io.readfile("build/standalone/" .. name) ~= text then
      io.writefile("build/standalone/" .. name, text)
   end
end

workspace "FusionFixUtils"
   configurations { "Release", "Debug" }
   platforms { "Win32", "x64" }
   location "build"
   objdir "build/obj/%{prj.name}/%{cfg.platform}/%{cfg.buildcfg}"
   targetdir "bin/%{cfg.platform}/%{cfg.buildcfg}"
   cppdialect "C++latest"
   characterset ("Unicode")
   buildoptions { "/utf-8", "/Zc:__cplusplus" }
   staticruntime "On"
   multiprocessorcompile ("On")
   warnings "Default"
   defines { "_CRT_SECURE_NO_WARNINGS" }

   filter "platforms:Win32"
      architecture "x86"
   filter "platforms:x64"
      architecture "x86_64"

   filter "configurations:Debug"
      defines { "DEBUG" }
      symbols "On"
   filter "configurations:Release"
      defines { "NDEBUG" }
      optimize "On"
      symbols "On"
   filter {}

-- What the headers need from the fixes' own dependencies (fetched into tests/external, never shipped from here)
function testdeps()
   includedirs { deps .. "/injector/include", deps .. "/injector/safetyhook/include", deps .. "/injector/zydis" }
   includedirs { deps .. "/hooking" }
   includedirs { "imgui" }
end

project "FusionFixUtilsTests"
   kind "ConsoleApp"
   language "C++"
   files { "tests/*.cpp", "tests/*.h" }
   files { "include/*", "overlay/*", "automation/*", "aa/*.hpp", "upscaler/*", "upscaler/bridge/*.h" }
   testdeps()
   files { deps .. "/injector/safetyhook/src/**.cpp", deps .. "/injector/zydis/Zydis.c" }
   files { deps .. "/hooking/Hooking.Patterns.cpp" }
   -- ImGui without a renderer: the overlay's frames in a hidden window (tests/overlay.cpp)
   files { "imgui/imgui.cpp", "imgui/imgui_draw.cpp", "imgui/imgui_tables.cpp", "imgui/imgui_widgets.cpp", "imgui/backends/imgui_impl_win32.cpp" }
   filter { "files:" .. deps .. "/** or imgui/**" }
      warnings "Off"
   filter {}
   links { "d3d9", "d3d11", "dxgi", "bcrypt", "psapi", "windowscodecs" }
   dependson { "CallbackProbe", "FakeHub" }

-- A DLL that nothing loads until a test does
project "CallbackProbe"
   kind "SharedLib"
   language "C++"
   files { "tests/probe/*.cpp" }

-- FusionFixHub.exe --upscaler without a GPU, in a folder of its own
project "FakeHub"
   kind "ConsoleApp"
   language "C++"
   targetdir "bin/%{cfg.platform}/%{cfg.buildcfg}/fakehub"
   targetname "FusionFixHub"
   files { "tests/fakehub/*.cpp", "upscaler/upscaler_bridge_protocol.h", "upscaler/bridge/upscaler_bridge_server.h" }

-- Every header on its own
project "StandaloneHeaders"
   kind "StaticLib"
   language "C++"
   files { "build/standalone/*.cpp" }
   testdeps()

-- The GPU side of the bridge, compiled when the vendor SDKs are given (the hub links it)
if _OPTIONS["upscaler-sdks"] then
   local sdks = path.getabsolute(_OPTIONS["upscaler-sdks"])
   project "BridgeServer"
      kind "StaticLib"
      language "C++"
      files { "upscaler/bridge/*.cpp", "upscaler/bridge/*.h", "upscaler/*.h" }
      includedirs { sdks .. "/dlss/include", sdks .. "/fidelityfx/api/include", sdks .. "/fidelityfx/upscalers/include" }
      defines { "WIN32_LEAN_AND_MEAN", "NOMINMAX" }
      filter "platforms:Win32"
         removefiles { "upscaler/bridge/*.cpp" }
      filter {}
end

